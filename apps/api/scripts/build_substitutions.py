"""Turn data/substitutions.csv into a migration (TYL-77).

    .venv/bin/python scripts/build_substitutions.py 20261112010000_substitutions_data

data/substitutions.csv is Sous's own swap guide, written for Sous from common
kitchen practice (no copied text). Columns:

* from, to: ingredient names as in the catalog (matched on lower(name)).
* factor: the recipe's amount times this. With to_unit and per, it's
  to_unit per one per of the recipe's ingredient ("1", "tbsp", "each": a
  tablespoon of flaxseed per egg); without them, the recipe's own unit.
* extras: "|"-separated ingredients used in small amounts (lemon juice to
  sour milk), put on the list without an amount.
* uses: any, baking or cooking. quality: good, or pinch (it works, but you'll
  notice).
* note: how to make the swap, in a sentence or two.

Each row's key is "from > to", plus " + extras" when there are any; it must be
unique, and re-running the build updates the swap with that key.
"""

import csv
import re
import sys
from pathlib import Path

API = Path(__file__).resolve().parents[1]
DATA = API / "data" / "substitutions.csv"
MIGRATIONS = API.parent.parent / "supabase" / "migrations"

USES = {"any", "baking", "cooking"}
QUALITY = {"good", "pinch"}
UNITS = {"each", "tsp", "tbsp", "cup", "oz", "lb", "g", "ml", "clove"}


def sql_text(s: str) -> str:
    """A SQL string literal."""
    return "'" + s.replace("'", "''") + "'"


def key(r: dict[str, str]) -> str:
    """A swap's stable key: "buttermilk > whole milk + lemon juice"."""
    extras = " + ".join(r["extras"].split("|")) if r["extras"] else ""
    return f"{r['from']} > {r['to']}" + (f" + {extras}" if extras else "")


def rows(path: Path = DATA) -> list[dict[str, str]]:
    """The checked rows of the data file, names lower-cased; stops the build
    with every problem found."""
    out: list[dict[str, str]] = []
    seen: set[str] = set()
    errors: list[str] = []
    for n, raw in enumerate(csv.DictReader(path.open(encoding="utf-8")), 2):
        if None in raw:
            errors.append(f"line {n}: too many fields (quote a note with commas)")
            continue
        r = {k: (v or "").strip() for k, v in raw.items()}
        for field in ("from", "to", "extras"):
            r[field] = r[field].lower()
        problems = []
        if not r["from"] or not r["to"] or r["from"] == r["to"]:
            problems.append("needs a from and a different to")
        try:
            if float(r["factor"]) <= 0:
                raise ValueError
        except ValueError:
            problems.append(f"bad factor {r['factor']!r}")
        if bool(r["to_unit"]) != bool(r["per"]):
            problems.append("to_unit and per go together")
        for unit in (r["to_unit"], r["per"]):
            if unit and unit not in UNITS:
                problems.append(f"unknown unit {unit!r}")
        if r["uses"] not in USES:
            problems.append(f"bad uses {r['uses']!r}")
        if r["quality"] not in QUALITY:
            problems.append(f"bad quality {r['quality']!r}")
        if not r["note"]:
            problems.append("no note")
        if r["extras"] and not all(re.fullmatch(r"[^|]+", x) for x in r["extras"].split("|")):
            problems.append(f"bad extras {r['extras']!r}")
        k = key(r)
        if k in seen:
            problems.append(f"{k!r} twice")
        seen.add(k)
        errors += [f"line {n}: {p}" for p in problems]
        out.append(r)
    if errors:
        sys.exit("\n".join(errors))
    return out


def migration(data: list[dict[str, str]]) -> str:
    """The rows as an upsert into substitutions, by key. Every name must be in
    the catalog: the migration fails otherwise, rather than dropping a swap."""

    def value(r: dict[str, str]) -> str:
        """One row of the values list."""
        extras = (
            "{" + ",".join(f'"{x}"' for x in r["extras"].split("|")) + "}" if r["extras"] else "{}"
        )
        unit = sql_text(r["to_unit"]) if r["to_unit"] else "null"
        per = sql_text(r["per"]) if r["per"] else "null"
        return (
            f"  ({sql_text(key(r))}, {sql_text(r['from'])}, {sql_text(r['to'])}, "
            f"{r['factor']}, {unit}, {per}, {sql_text(extras)}::text[], "
            f"{sql_text(r['uses'])}, {sql_text(r['quality'])}, {sql_text(r['note'])})"
        )

    values = ",\n".join(value(r) for r in data)
    return f"""-- Substitutions, from apps/api/data/substitutions.csv; generated by
-- apps/api/scripts/build_substitutions.py. Don't edit this file once applied.

do $$
declare
  v_missing text;
begin
  create temp table swap_rows (
    key text, from_name text, to_name text, factor numeric, to_unit text,
    per_unit text, extras text[], uses text, quality text, note text
  ) on commit drop;
  insert into swap_rows values
{values};

  -- Every name must be an ingredient.
  select string_agg(distinct n, ', ') into v_missing
  from (
    select from_name as n from swap_rows
    union select to_name from swap_rows
    union select unnest(extras) from swap_rows
  ) names
  where not exists (select 1 from public.ingredients i where lower(i.name) = names.n);
  if v_missing is not null then
    raise exception 'substitutions name unknown ingredients: %', v_missing;
  end if;

  insert into public.substitutions (key, from_ingredient_id, to_ingredient_id, factor,
    to_unit, per_unit, extras, uses, quality, note)
  select s.key, f.id, t.id, s.factor, s.to_unit, s.per_unit,
    coalesce((select array_agg(i.id order by x.n)
              from unnest(s.extras) with ordinality as x(name, n)
              join public.ingredients i on lower(i.name) = x.name), '{{}}'),
    s.uses, s.quality, s.note
  from swap_rows s
  join public.ingredients f on lower(f.name) = s.from_name
  join public.ingredients t on lower(t.name) = s.to_name
  on conflict (key) do update set
    from_ingredient_id = excluded.from_ingredient_id,
    to_ingredient_id = excluded.to_ingredient_id, factor = excluded.factor,
    to_unit = excluded.to_unit, per_unit = excluded.per_unit, extras = excluded.extras,
    uses = excluded.uses, quality = excluded.quality, note = excluded.note;
end
$$;
"""


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    out = MIGRATIONS / f"{sys.argv[1]}.sql"
    if out.exists():
        sys.exit(f"{out.name} exists; migrations are append-only, pick a new name")
    data = rows()
    out.write_text(migration(data))
    print(f"wrote {out.name}: {len(data)} swaps")
