"""Turn data/seasonality.csv into a migration (TYL-70).

    .venv/bin/python scripts/build_seasonality.py 20261022010000_seasonality

data/seasonality.csv says, for each ingredient and region, the months it's in
season (1-12, space-separated), and which crop of the source it comes from:

* region "US": the USDA SNAP-Ed Seasonal Produce Guide, the national baseline
  (https://snaped.fna.usda.gov/resources/nutrition-education-materials/seasonal-produce-guide).
  It lists produce by season; winter is Dec-Feb, spring Mar-May, summer
  Jun-Aug, fall Sep-Nov.
* a state ("NC"): that state's own chart, read month by month. NC is the NC
  Department of Agriculture's "What's in Season? North Carolina Fruit and
  Vegetable Availability" chart (https://ncagr.gov/marketing/produce-availability-chart/open).

A user's region is their home zip's state when there's a chart for it, else
"US" (season_region() in the migration). Adding a state: add its rows here,
add its zip range to season_region(), and write a new migration.
"""

import csv
import sys
from pathlib import Path

API = Path(__file__).resolve().parents[1]
DATA = API / "data" / "seasonality.csv"
MIGRATIONS = API.parent.parent / "supabase" / "migrations"


def sql_text(s: str) -> str:
    """A SQL string literal."""
    return "'" + s.replace("'", "''") + "'"


def rows() -> list[dict[str, str]]:
    """The checked rows of the data file: months 1-12, no duplicates."""
    out, seen, errors = [], set(), []
    for n, r in enumerate(csv.DictReader(DATA.open(encoding="utf-8")), 2):
        key = (r["ingredient"], r["region"])
        months = [int(m) for m in r["months"].split()]
        if key in seen:
            errors.append(f"line {n}: {key} twice")
        if not months or any(m < 1 or m > 12 for m in months):
            errors.append(f"line {n}: bad months {r['months']!r}")
        seen.add(key)
        out.append(r)
    if errors:
        sys.exit("\n".join(errors))
    return out


def migration(data: list[dict[str, str]]) -> str:
    """The rows as an upsert into ingredient_seasons."""
    values = ",\n".join(
        f"  ({sql_text(r['ingredient'])}, {sql_text(r['region'])}, "
        f"'{{{','.join(r['months'].split())}}}'::smallint[])"
        for r in data
    )
    return f"""-- Seasonal produce by region, from apps/api/data/seasonality.csv; generated by
-- apps/api/scripts/build_seasonality.py (sources cited there). Don't edit
-- this file once applied.

insert into public.ingredient_seasons (ingredient_id, region, months)
select i.id, v.region, v.months
from (values
{values}
) as v(name, region, months)
join public.ingredients i on lower(i.name) = v.name
on conflict (ingredient_id, region) do update set months = excluded.months;
"""


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    out = MIGRATIONS / f"{sys.argv[1]}.sql"
    if out.exists():
        sys.exit(f"{out.name} exists; migrations are append-only, pick a new name")
    data = rows()
    out.write_text(migration(data))
    print(f"wrote {out.name}: {len(data)} rows")
