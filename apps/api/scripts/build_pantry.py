"""Turn data/pantry.csv into a migration (TYL-134, TYL-135).

    .venv/bin/python scripts/build_pantry.py 20261022040000_pantry_data

data/pantry.csv lists the pantry-type ingredients (shelf-stable things people
keep: spices, oils, baking, sauces, grains, cans, broths, nuts) with:

* group: the aisle group the pantry page shows it under;
* kits: the starter kits it's in, space-separated. "basics" is offered to
  everyone; a cuisine's slug (indian, thai...) to people who love that
  cuisine; a diet's slug (vegan, gluten_free...) to people who eat that way.

The migration sets ingredients.pantry_group and fills pantry_kits, and fails
if a name doesn't match an ingredient, so a typo can't drop a row unnoticed.
"""

import csv
import re
import sys
from pathlib import Path

API = Path(__file__).resolve().parents[1]
DATA = API / "data" / "pantry.csv"
MIGRATIONS = API.parent.parent / "supabase" / "migrations"

# The groups the pantry page shows, as the database's check allows them.
GROUPS = {"spices", "oils_vinegars", "baking", "sauces", "grains", "cans", "broths", "nuts"}


def sql_text(s: str) -> str:
    """A SQL string literal."""
    return "'" + s.replace("'", "''") + "'"


def rows(path: Path = DATA) -> list[dict[str, str]]:
    """The checked rows of the data file: a lower-cased ingredient name (the
    migration matches lower(name)) listed once, a known group, and kit names
    of lower-case letters and underscores."""
    out, seen, errors = [], set(), []
    for n, r in enumerate(csv.DictReader(path.open(encoding="utf-8")), 2):
        name = r["ingredient"].strip().lower()
        kits = r["kits"].split()
        if not name:
            errors.append(f"line {n}: no ingredient name")
        if name in seen:
            errors.append(f"line {n}: {name!r} twice")
        if r["group"] not in GROUPS:
            errors.append(f"line {n}: unknown group {r['group']!r}")
        bad = [k for k in kits if not re.fullmatch(r"[a-z_]+", k)]
        if bad or len(set(kits)) != len(kits):
            errors.append(f"line {n}: bad kits {r['kits']!r}")
        seen.add(name)
        out.append({"ingredient": name, "group": r["group"], "kits": " ".join(kits)})
    if errors:
        sys.exit("\n".join(errors))
    return out


def migration(data: list[dict[str, str]]) -> str:
    """The rows as group updates and kit inserts, checked to all match."""
    groups = ",\n".join(f"  ({sql_text(r['ingredient'])}, {sql_text(r['group'])})" for r in data)
    kit_rows = [
        f"  ({sql_text(r['ingredient'])}, {sql_text(k)})" for r in data for k in r["kits"].split()
    ]
    joined = ",\n".join(kit_rows)
    kits = f"insert into pantry_kit_rows values\n{joined};\n" if kit_rows else ""
    return f"""-- Pantry groups and starter kits, from apps/api/data/pantry.csv; generated by
-- apps/api/scripts/build_pantry.py. Don't edit this file once applied.

create temporary table pantry_groups (name text primary key, grp text not null);
insert into pantry_groups values
{groups};

create temporary table pantry_kit_rows (name text, kit text);
{kits}
do $$
declare
  missing text;
begin
  select string_agg(g.name, ', ') into missing
  from pantry_groups g
  where not exists (select 1 from public.ingredients i where lower(i.name) = g.name);
  if missing is not null then
    raise exception 'pantry.csv names no ingredient: %', missing;
  end if;
end
$$;

update public.ingredients i set pantry_group = g.grp
from pantry_groups g where lower(i.name) = g.name;

insert into public.pantry_kits (kit, ingredient_id)
select k.kit, i.id
from pantry_kit_rows k join public.ingredients i on lower(i.name) = k.name
on conflict do nothing;

drop table pantry_groups, pantry_kit_rows;
"""


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    out = MIGRATIONS / f"{sys.argv[1]}.sql"
    if out.exists():
        sys.exit(f"{out.name} exists; migrations are append-only, pick a new name")
    data = rows()
    out.write_text(migration(data))
    print(f"wrote {out.name}: {len(data)} ingredients")
